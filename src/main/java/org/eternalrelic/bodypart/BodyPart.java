package org.eternalrelic.bodypart;

/**
 * <h1>玩家身上的六个部位</h1>
 *
 * <p>把玩家从头到脚切成六块，用来回答「这一箭到底射在哪儿」。</p>
 *
 * <p>每一块的具体范围不在这个枚举里，而是由 {@link BodyPartResolver 判定类} 照着玩家模型用一组
 * 三维方块划定的——头、躯干上下两截、两侧肩膀、以及腿脚。</p>
 *
 * <p>枚举声明顺序为<b>从下到上</b>，与判定时从脚底往头顶依次比较的顺序一致。</p>
 */
public enum BodyPart {

    /** 腿部：身体最下面约三分之一。 */
    LEGS,

    /** 腹部：身体中段，约在身高的 33% 到 56% 之间。 */
    ABDOMEN,

    /** 正胸：上半身的中段，也就是身体正中间那一条。 */
    CHEST,

    /** 左肩：上半身偏向玩家自身左手边的那一侧。 */
    LEFT_SHOULDER,

    /** 右肩：上半身偏向玩家自身右手边的那一侧。 */
    RIGHT_SHOULDER,

    /** 头部：身体最上面约 22% 的高度。 */
    HEAD
}
