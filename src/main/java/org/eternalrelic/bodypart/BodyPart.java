package org.eternalrelic.bodypart;

/**
 * <h1>玩家身上的七个部位</h1>
 *
 * <p>把玩家从头到脚切成七块，用来回答「这一箭到底射在哪儿」「这一刀砍在哪一边」。</p>
 *
 * <p>每一块的具体范围不在这个枚举里，而是由 {@link BodyPartResolver 判定类} 照着玩家模型用一组
 * 三维方块划定的——头、躯干的前后两半、两侧肩膀、以及腿脚。</p>
 *
 * <p><b>前后是分得开的</b>：{@link #CHEST 正胸}与 {@link #ABDOMEN 腹部}只占躯干的<b>前半</b>，
 * {@link #BACK 后背}占<b>后半</b>。所以从背后偷袭和正面硬拼会落到不同的部位上——
 * 前者摸到后背，后者摸到正胸。</p>
 *
 * <p>枚举里没有「后腰」这一块：躯干后半是<b>整块</b>算作后背。腰与肩胛在挨打这件事上没有什么
 * 需要分开的理由，多切一块只会让概率更碎。</p>
 */
public enum BodyPart {

    /** 腿部：身体最下面约三分之一。 */
    LEGS,

    /** 腹部：躯干下半的<b>前面</b>那一片。 */
    ABDOMEN,

    /** 后背：躯干<b>后面</b>整块，从腰到肩胛。 */
    BACK,

    /** 正胸：躯干上半的<b>前面</b>那一片。 */
    CHEST,

    /** 左肩：上半身偏向玩家自身左手边的那一侧。 */
    LEFT_SHOULDER,

    /** 右肩：上半身偏向玩家自身右手边的那一侧。 */
    RIGHT_SHOULDER,

    /** 头部：身体最上面约 22% 的高度。 */
    HEAD
}
